//relational operator
#include<stdio.h>
int main()
{
	int num1;
	int num2;
	printf("enter number1");
	scanf("%d",&num1);
	printf("enter number2");
	scanf("%d",&num2);
	printf("%d",num1>num2);
	printf("\n%d",num1<num2);
	printf("\n%d",num1>=num2);
	printf("\n%d",num1<=num2);
	printf("\n%d",num1==num2);
	printf("\n%d",num1!=num2);
}
